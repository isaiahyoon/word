export function applyUiLocale(locale, root = document) {
  const text = (selector, key, preserveChildren = false) => {
    const element = root.querySelector(selector);
    if (!element) return;
    const value = formatUiText(locale, key);
    if (preserveChildren && element.firstChild?.nodeType === 3) {
      element.firstChild.nodeValue = `${value} `;
    } else {
      element.textContent = value;
    }
  };
  for (const [selector, key, preserveChildren] of TEXT_BINDINGS) {
    text(selector, key, preserveChildren);
  }
  for (const [selector, attribute, key] of ATTRIBUTE_BINDINGS) {
    const element = root.querySelector(selector);
    if (!element) continue;
    const values = element.matches(".shortcut-row--home kbd, .shortcut-row--old-testament kbd, .shortcut-row--new-testament kbd, .shortcut-row--quiet kbd")
      ? { key: element.textContent.trim() }
      : {};
    element.setAttribute(attribute, formatUiText(locale, key, values));
  }
  root.querySelectorAll("[data-ui-text]").forEach((element) => {
    element.textContent = formatUiText(locale, element.dataset.uiText);
  });
  for (const [dataName, attribute] of [
    ["uiAriaLabel", "aria-label"],
    ["uiTitle", "title"],
    ["uiPlaceholder", "placeholder"],
  ]) {
    root.querySelectorAll(`[data-${dataName.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}]`).forEach((element) => {
      element.setAttribute(attribute, formatUiText(locale, element.dataset[dataName]));
    });
  }
}