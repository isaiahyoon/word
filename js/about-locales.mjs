export function getEditionSummary(locale, language, editions) {
  const registered = Object.values(editions);
  const names = new Intl.ListFormat(language, { style: "long", type: "conjunction" })
    .format(registered.map((edition) => edition.label));
  return {
    ...locale,
    editionsTitle: locale.editionsTitle.replace("{count}", new Intl.NumberFormat(language).format(registered.length)),
    editionsCopy: locale.editionsCopy.replace("{editions}", names),
  };
}
